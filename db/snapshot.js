#!/usr/bin/env node
/**
 * Regenerates db/schema.sql (structure only) from the migrated dev database.
 * Uses pg_dump inside the dev container so no local Postgres client is needed.
 *   npm run db:snapshot        (container name override: PG_CONTAINER=...)
 * schema.sql is a READ-ONLY reference: change the schema with a new migration.
 */
const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');
require('dotenv').config({ path: path.join(__dirname, '..', '.env') });

const container = process.env.PG_CONTAINER || 'bb-postgres-dev';
const user = process.env.POSTGRES_USER || 'bb';
const dbName = process.env.POSTGRES_DB || 'balloonsbuzz';

const dump = execFileSync('docker', [
  'exec', container, 'pg_dump', '-s', '--no-owner', '--no-privileges', '--no-comments', '-U', user, dbName,
], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });

const body = dump
  .split('\n')
  .filter((l) => !/^SELECT pg_catalog\.set_config\('search_path'/.test(l))
  .filter((l) => !/^\\(un)?restrict /.test(l))   // pg_dump 15.14+ session tokens (random per run)
  .join('\n')
  .replace(/\n{3,}/g, '\n\n');

const header = `-- BalloonsBuzz WhatsApp Platform: database schema snapshot
-- GENERATED by \`npm run db:snapshot\` from db/migrations. Do not edit by hand.
-- Engine: PostgreSQL 15 + pgvector (same as Whapter).
`;
fs.writeFileSync(path.join(__dirname, 'schema.sql'), header + body);
console.log(`Wrote db/schema.sql (${body.split('\n').length} lines)`);
